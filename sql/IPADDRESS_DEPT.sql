  DEPT_ID      VARCHAR2(20 BYTE),
  DEPT_NAME    VARCHAR2(255 BYTE),
  IP_ALL       VARCHAR2(100 BYTE),
  IP_RANGE1    VARCHAR2(20 BYTE),
  IP_RANGE2    VARCHAR2(20 BYTE),
  CATID        VARCHAR2(100 BYTE),
  CANCEL_FLG   VARCHAR2(1 BYTE),
  CREATE_DATE  DATE                             DEFAULT sysdate,
  UPDATE_DATE  DATE
)
